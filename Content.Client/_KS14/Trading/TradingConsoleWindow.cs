using System;
using System.Collections.Generic;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Guidebook;
using Content.Shared._KS14.Trading;
using Content.Shared.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client._KS14.Trading;

/// <summary>
/// Corporate trading workstation. XAML controls the layout and cards; the code-behind
/// only adds live rows and interprets server-authoritative account/market state.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TradingConsoleWindow : FancyWindow
{
    public event Action<string, int, bool>? OnTrade;
    public event Action<int>? OnWithdraw;
    public event Action<string, TradingOrderType, int, int, int>? OnPendingOrder;
    public event Action<int>? OnCancelPendingOrder;
    public event Action? OnCardAction;

    private TradingConsoleUiState? _state;
    private string _selectedSymbol = "NT";
    private int _historySamples = 20;
    private int _orderDurationMinutes = 15;
    private readonly Dictionary<string, string> _enteredQuantities = new();

    public TradingConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, "ACCOUNT");
        Tabs.SetTabTitle(1, "MARKET");
        Tabs.SetTabTitle(2, "ORDERS");
        Tabs.SetTabTitle(3, "NANONEWS");

        CardButton.OnPressed += _ => OnCardAction?.Invoke();
        WithdrawButton.OnPressed += _ =>
        {
            if (!int.TryParse(WithdrawAmount.Text.Trim(), out var amount) || amount <= 0)
            {
                SetText(WithdrawNotice, "Enter a positive whole number of spesos.");
                return;
            }

            OnWithdraw?.Invoke(amount);
        };

        GuideButton.OnPressed += _ => UserInterfaceManager
            .GetUIController<GuidebookUIController>()
            .OpenGuidebook(selected: new ProtoId<GuideEntryPrototype>("TradingStockExchange"));

        LineButton.OnPressed += _ => PriceGraph.ChartType = TradingChartType.Line;
        BarButton.OnPressed += _ => PriceGraph.ChartType = TradingChartType.Bar;
        CandleButton.OnPressed += _ => PriceGraph.ChartType = TradingChartType.Candle;
        OneMinuteButton.OnPressed += _ => SetChartPeriod(4);
        FiveMinuteButton.OnPressed += _ => SetChartPeriod(20);
        FifteenMinuteButton.OnPressed += _ => SetChartPeriod(60);
        AllButton.OnPressed += _ => SetChartPeriod(0);

        PriceGraph.OnSampleSelected += (index, value) =>
        {
            var time = index < PriceGraph.HistoryTimes.Length
                ? PriceGraph.HistoryTimes[index]
                : index * 15;
            var story = _state?.NewsHistory
                .Where(n => n.Symbol == _selectedSymbol &&
                    Math.Abs(n.PublishedSeconds - time) <= 120)
                .OrderBy(n => Math.Abs(n.PublishedSeconds - time))
                .FirstOrDefault();
            var related = story == null ? "No NanoNews near this price." : $"NanoNews: {story.Title} — {story.Description}";
            SetText(GraphDetails, $"SELECTED QUOTE   t+{time / 60:00}:{time % 60:00}   {value:N0} sp\n{related}");
        };

        SearchField.OnTextChanged += _ => RefreshQuotes();

        ExpireFive.OnPressed += _ => SetExpiry(5);
        ExpireFifteen.OnPressed += _ => SetExpiry(15);
        ExpireThirty.OnPressed += _ => SetExpiry(30);
        LimitBuyButton.OnPressed += _ => SubmitPending(TradingOrderType.LimitBuy);
        LimitSellButton.OnPressed += _ => SubmitPending(TradingOrderType.LimitSell);
        StopLossButton.OnPressed += _ => SubmitPending(TradingOrderType.StopLoss);

        SetText(GraphDetails, "Select a point on the graph to inspect its recorded price and related NanoNews.");
        SetText(WithdrawNotice, "Use the Trading Guide for deposits, withdrawals and account instructions.");
        SetText(NewsStory, "Select a NanoNews bulletin below to read the full story.");
    }

    private static void SetText(RichTextLabel label, string value)
    {
        label.SetMessage(FormattedMessage.FromUnformatted(value));
    }

    private static PanelContainer Card()
    {
        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#192736"),
                BorderColor = Color.FromHex("#344b60"),
                BorderThickness = new Thickness(1)
            }
        };
    }

    private static Label TextLabel(string text, bool expand = false)
    {
        return new Label { Text = text, HorizontalExpand = expand };
    }

    private void SetChartPeriod(int samples)
    {
        _historySamples = samples;
        RefreshChart();
    }

    private void SetExpiry(int minutes)
    {
        _orderDurationMinutes = minutes;
        RefreshOrderSymbol();
    }

    private void RefreshOrderSymbol()
    {
        OrderSymbolLabel.Text = $"{_selectedSymbol}  /  Expires in {_orderDurationMinutes} minutes";
    }

    public void UpdateState(TradingConsoleUiState state)
    {
        _state = state;
        AccountLabel.Text = state.HasCard ? state.CardName : "ID CARD REQUIRED";
        BalanceLabel.Text = $"AVAILABLE {state.Balance:N0} sp  /  RESERVED {state.ReservedCash:N0} sp";
        PortfolioLabel.Text =
            $"TOTAL {state.PortfolioValue:N0} sp  /  UNREALIZED {state.UnrealizedProfit:+#,0;-#,0;0} sp  /  REALIZED {state.RealizedProfit:+#,0;-#,0;0} sp";
        WithdrawButton.Disabled = !state.HasCard || state.Balance <= 0;
        SetText(WithdrawNotice, string.IsNullOrWhiteSpace(state.Notice)
            ? "Available cash excludes money reserved for pending orders."
            : state.Notice);
        SetText(LatestNews, state.News);
        RefreshOrderSymbol();
        RefreshChart();
        RefreshQuotes();
        RefreshPendingOrders();
        RefreshNewsArchive();
    }

    private void RefreshChart()
    {
        var quote = _state?.Quotes.FirstOrDefault(x => x.Symbol == _selectedSymbol);
        if (quote == null)
            return;

        PriceGraph.History = quote.History;
        PriceGraph.HistoryTimes = quote.HistoryTimes;
        PriceGraph.EventTimes = _state!.NewsHistory
            .Where(n => n.Symbol == quote.Symbol)
            .Select(n => n.PublishedSeconds)
            .ToArray();
        PriceGraph.SamplesToShow = _historySamples;

        ChartNameLabel.Text = $"{quote.Name.ToUpperInvariant()}  /  {quote.Symbol}";
        ChartPriceLabel.Text = $"{quote.Price:N0} sp     BID {quote.Bid:N0}     ASK {quote.Ask:N0}";

        var risk = quote.VolatilityPercent < 1 ? "LOW" :
            quote.VolatilityPercent < 4 ? "MODERATE" :
            quote.VolatilityPercent < 12 ? "HIGH" : "EXTREME";
        MarketStatusLabel.Text = quote.HaltSeconds > 0
            ? $"TRADING HALTED  {quote.HaltSeconds}s"
            : "●  MARKET OPEN";
        MarketStatusLabel.FontColorOverride = quote.HaltSeconds > 0
            ? Color.FromHex("#ff867d")
            : Color.FromHex("#66dfaa");
        MarketRiskLabel.Text = $"VOLATILITY {risk}  {quote.VolatilityPercent:F1}%";
        SetText(MarketDetails,
            $"CHANGE {quote.ChangePercent:+0.0;-0.0;0}%     SPREAD {quote.Spread} sp     " +
            $"LIQUIDITY {quote.Liquidity:N0} shares\n" +
            $"VOLUME {quote.Volume:N0}     MARKET CAP {quote.MarketCap:N0} sp     " +
            $"OWNED {quote.Held:N0}     AVG COST {quote.AverageCost:N1} sp");
    }

    private void RefreshQuotes()
    {
        QuoteList.RemoveAllChildren();
        if (_state == null)
            return;

        var filter = SearchField.Text.Trim();
        foreach (var quote in _state.Quotes.Where(q =>
                     q.Symbol.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                     q.Name.Contains(filter, StringComparison.OrdinalIgnoreCase)))
        {
            var panel = Card();
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Margin = new Thickness(10, 8),
                SeparationOverride = 9,
                HorizontalExpand = true
            };
            panel.AddChild(row);

            var select = new Button { Text = quote.Symbol, MinWidth = 62 };
            select.OnPressed += _ =>
            {
                _selectedSymbol = quote.Symbol;
                RefreshChart();
                RefreshOrderSymbol();
            };
            row.AddChild(select);

            var name = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
            name.AddChild(TextLabel(quote.Name));
            name.AddChild(TextLabel(quote.HaltSeconds > 0 ? $"HALTED {quote.HaltSeconds}s" :
                $"Bid {quote.Bid}  /  Ask {quote.Ask}  /  Held {quote.Held}"));
            row.AddChild(name);

            row.AddChild(TextLabel($"{quote.Price:N0} sp"));
            var qty = new LineEdit
            {
                Text = _enteredQuantities.TryGetValue(quote.Symbol, out var entered) ? entered : "1",
                MinWidth = 50,
                SetWidth = 62,
                PlaceHolder = "Qty"
            };
            qty.OnTextChanged += _ => _enteredQuantities[quote.Symbol] = qty.Text;
            row.AddChild(qty);

            var buy = new Button { Text = "BUY", Disabled = quote.HaltSeconds > 0 || _state.HasCard == false };
            var sell = new Button { Text = "SELL", Disabled = quote.HaltSeconds > 0 || _state.HasCard == false };
            buy.OnPressed += _ => SubmitMarket(quote.Symbol, qty.Text, true);
            sell.OnPressed += _ => SubmitMarket(quote.Symbol, qty.Text, false);
            row.AddChild(buy);
            row.AddChild(sell);
            QuoteList.AddChild(panel);
        }
    }

    private void SubmitMarket(string symbol, string quantity, bool buy)
    {
        if (int.TryParse(quantity, out var count) && count is >= 1 and <= 1000)
            OnTrade?.Invoke(symbol, count, buy);
    }

    private void SubmitPending(TradingOrderType type)
    {
        if (_state?.HasCard != true ||
            !int.TryParse(OrderQuantity.Text, out var qty) || qty is < 1 or > 1000 ||
            !int.TryParse(OrderPrice.Text, out var price) || price is < 1 or > 1000000)
            return;
        OnPendingOrder?.Invoke(_selectedSymbol, type, qty, price, _orderDurationMinutes);
    }

    private void RefreshPendingOrders()
    {
        OrderList.RemoveAllChildren();
        if (_state?.HasCard != true)
        {
            OrderList.AddChild(TextLabel("Insert ID to access conditional orders."));
            return;
        }

        foreach (var order in _state.Orders)
        {
            var panel = Card();
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Margin = new Thickness(8, 6),
                SeparationOverride = 8
            };
            panel.AddChild(row);
            row.AddChild(TextLabel($"#{order.Id}  {order.Symbol}  {order.Type}  x{order.Quantity}  " +
                $"@ {order.TriggerPrice} sp  /  {order.ExpiresInSeconds / 60}m {order.ExpiresInSeconds % 60}s", true));
            var cancel = new Button { Text = "CANCEL" };
            cancel.OnPressed += _ => OnCancelPendingOrder?.Invoke(order.Id);
            row.AddChild(cancel);
            OrderList.AddChild(panel);
        }
    }

    private void RefreshNewsArchive()
    {
        NewsList.RemoveAllChildren();
        if (_state == null)
            return;

        foreach (var entry in _state.NewsHistory.Reverse())
        {
            var panel = Card();
            var col = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                Margin = new Thickness(12, 8),
                SeparationOverride = 5
            };
            panel.AddChild(col);
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal };
            var headline = new RichTextLabel { MaxWidth = 740, HorizontalExpand = true };
            SetText(headline, $"t+{entry.PublishedSeconds / 60:00}:{entry.PublishedSeconds % 60:00}  " +
                $"[{entry.Symbol}]  {entry.Title}");
            row.AddChild(headline);

            var read = new Button { Text = "READ", MinWidth = 70 };
            read.OnPressed += _ =>
            {
                var outcome = entry.ResolvedSeconds == null
                    ? "Reaction pending"
                    : $"Reaction {entry.ActualImpactPercent:+0.0;-0.0;0}%";
                SetText(NewsStory,
                    $"NANONEWS  /  {entry.Symbol}  /  t+{entry.PublishedSeconds / 60:00}:{entry.PublishedSeconds % 60:00}\n\n" +
                    $"{entry.Title}\n\n{entry.Description}\n\n{outcome}");
                _selectedSymbol = entry.Symbol;
                RefreshChart();
                RefreshOrderSymbol();
            };
            row.AddChild(read);
            col.AddChild(row);

            var small = new RichTextLabel { MaxWidth = 840, HorizontalExpand = true };
            SetText(small, entry.ResolvedSeconds == null ? "AWAITING MARKET RESPONSE"
                : $"MARKET RESPONSE {entry.ActualImpactPercent:+0.0;-0.0;0}%");
            col.AddChild(small);
            NewsList.AddChild(panel);
        }
    }
}
